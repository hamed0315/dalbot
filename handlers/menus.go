package handlers

import (
	"fmt"

	"dalbot/api"
)

// showHelpMenu نمایش منوی اصلی راهنما (با دکمه‌های دسته‌بندی)
func showHelpMenu(chatID string, messageID int, firstName string) {
	text := fmt.Sprintf("✨ %s عزیز، به راهنمای جامع دال خوش آمدی!\n\n🎯 یکی از بخش‌های زیر را انتخاب کنید:", firstName)

	keyboard := api.InlineKeyboardMarkup{
		InlineKeyboard: [][]api.InlineKeyboardButton{
			{
				{Text: "🛡️ قفل‌ها", CallbackData: "help:locks"},
				{Text: "👥 مدیریت کاربران", CallbackData: "help:users"},
			},
			{
				{Text: "⚙️ تنظیمات ضداسپم", CallbackData: "help:antispam"},
				{Text: "🔗 لینک و دعوت", CallbackData: "help:invite"},
			},
			{
				{Text: "📊 آمار و رنکینگ", CallbackData: "help:stats"},
				{Text: "🧠 هوش مصنوعی", CallbackData: "help:ai"},
			},
			{
				{Text: "📌 سایر دستورات", CallbackData: "help:other"},
			},
			{
				{Text: "❌ بستن", CallbackData: "help:close"},
			},
		},
	}

	api.EditMessageText(chatID, messageID, text, &keyboard)
}

// showHelpSection نمایش یک بخش خاص از راهنما (با دکمه بازگشت و بستن)
func showHelpSection(chatID string, messageID int, section string, firstName string) {
	var text string

	switch section {
	case "locks":
		text = "🛡️ **راهنمای قفل‌های محتوا**\n\n" +
			"دال می‌تواند ۱۱ نوع پیام مختلف را به‌طور خودکار حذف کند.\n\n" +
			"✅ **فعال‌سازی:** `قفل [نوع]`\n" +
			"❌ **غیرفعال‌سازی:** `باز [نوع]`\n\n" +
			"📌 **لیست کامل:**\n" +
			"• لینک • فوروارد • تبلیغات • عکس • ویدئو\n" +
			"• صوت • متن طولانی • استیکر • گیف\n" +
			"• نظرسنجی (حتی ناشناس!) • قفل گروه\n\n" +
			"⚙️ **تنظیم جریمه:** از پنل شیشه‌ای می‌توانید برای هر قفل جریمهٔ جداگانه (حذف، اخطار، سکوت، بن) تعیین کنید.\n" +
			"✨ **نکتهٔ حرفه‌ای:** در حملات سنگین، دال به‌طور خودکار جریمهٔ برخی قفل‌ها را به بن تغییر می‌دهد."

	case "users":
		text = "👥 **مدیریت کاربران**\n\n" +
			"• `.اخطار` (ریپلای) – ثبت اخطار (۳ اخطار = بن خودکار)\n" +
			"• `.حذف اخطار` (ریپلای، ID، یا @username)\n" +
			"• `.بن` / `.کیک` / `.صیک` (ریپلای) – اخراج کاربر\n" +
			"• `.انبن` (ریپلای، ID، یا @username) – آزاد کردن کاربر بن‌شده\n" +
			"• `.سکوت [دقیقه]` (ریپلای) – محدود کردن کاربر\n" +
			"• `.رفع سکوت` (ریپلای، ID، یا @username)\n" +
			"• `.رفع سکوت همه` – آزاد کردن همه\n" +
			"• `ترفیع` / `تنزیل` / `ویژه` – مدیریت مقام‌ها\n" +
			"• `ثبت اصل` / `اصل` / `معرفی` – بیوگرافی کاربران\n" +
			"• `فیلتر <کلمه>` / `حذف فیلتر <کلمه>` / `لیست فیلتر` – مدیریت کلمات ممنوعه\n\n" +
			"✨ **نکته:** ادمین‌های ارشد و مالک می‌توانند از پنل شیشه‌ای نیز کاربران را مدیریت کنند."

	case "antispam":
		text = "⚙️ **تنظیمات ضداسپم**\n\n" +
			"دال دارای سیستم ضداسپم چندلایه با قابلیت یادگیری است.\n\n" +
			"• `تنظیم اسپم سیل <تعداد> <ثانیه>` – حساسیت به پیام‌های پشت‌سرهم\n" +
			"• `تنظیم اسپم تکرار <حداکثر>` – حساسیت به پیام‌های تکراری\n" +
			"• `تنظیم اسپم سکوت <ساعت>` – جریمهٔ سکوت برای اسپم\n" +
			"• `تنظیم اسپم اخراج` – تغییر جریمه به بن\n\n" +
			"📊 برای مشاهده تنظیمات فعلی از دستور `آمار` استفاده کنید.\n" +
			"🧠 از پنل شیشه‌ای می‌توانید هوش مصنوعی را روشن/خاموش کنید."

	case "invite":
		text = "🔗 **لینک و دعوت**\n\n" +
			"• `لینک` – نمایش منوی لینک (هوشمند دال یا عادی گروه)\n" +
			"• `ساخت دعوت` – ساخت لینک هوشمند جدید\n" +
			"• `باطل کردن دعوت` – باطل کردن لینک هوشمند فعلی\n\n" +
			"🔗 **عضویت اجباری:**\n" +
			"• `عضویت اجباری @کانال` – افزودن کانال\n" +
			"• `حذف عضویت اجباری @کانال` – حذف کانال\n" +
			"• `لیست عضویت اجباری` – نمایش کانال‌ها\n\n" +
			"✨ کاربران برای ورود به گروه باید عضو کانال‌های اجباری شوند."

	case "stats":
		text = "📊 **آمار و رنکینگ**\n\n" +
			"• `رنکینگ` – ۲۰ کاربر برتر روز\n" +
			"• `آمار` – ۱۰ بن، اخطار، سکوت اخیر + فعال‌ترین ادمین‌ها\n" +
			"• `تگ` – منوی تگ همه و تگ فعالان (با منشن واقعی)\n" +
			"• `قوانین` – مشاهده قوانین گروه\n\n" +
			"📌 **نکته:** رنکینگ هر ۲۴ ساعت ریست می‌شود."

	case "ai":
		text = "🧠 **هوش مصنوعی دال**\n\n" +
			"دال دارای یک مغز یادگیرنده است که از اسپم‌های قبلی درس می‌گیرد.\n\n" +
			"🔹 این سیستم بی‌صدا در پس‌زمینه کار می‌کند و دقت تشخیص اسپم را بالا می‌برد.\n" +
			"🔹 ادمین می‌تواند از پنل ضداسپم، این قابلیت را موقتاً غیرفعال کند.\n" +
			"🔹 هیچ دادهٔ شخصی ذخیره نمی‌شود—فقط الگوهای اسپم یاد گرفته می‌شود.\n\n" +
			"✨ **پیشنهاد:** این گزینه را همیشه فعال نگه دارید تا دال باهوش‌تر شود."

	case "other":
		text = "📌 **سایر دستورات**\n\n" +
			"• `پاکسازی <تعداد>` – حذف پیام‌ها (حداکثر ۵۰۰)\n" +
			"• `.پین` / `.حذف پین` – مدیریت پیام‌های سنجاق‌شده\n" +
			"• `نصب` – فعال‌سازی ربات در گروه\n" +
			"• `راهنما` – همین منو\n\n" +
			"🆘 **هشدار امنیتی:**\n" +
			"اگر مالک گروه از کانال‌های حمایتی خارج شود، ربات غیرفعال می‌شود."
	}

	backButton := api.InlineKeyboardButton{
		Text:         "🔙 بازگشت به منوی اصلی",
		CallbackData: fmt.Sprintf("help:main:%d", messageID),
	}
	closeButton := api.InlineKeyboardButton{
		Text:         "❌ بستن",
		CallbackData: "help:close",
	}

	keyboard := api.InlineKeyboardMarkup{
		InlineKeyboard: [][]api.InlineKeyboardButton{
			{backButton, closeButton},
		},
	}

	api.EditMessageText(chatID, messageID, text, &keyboard)
}
